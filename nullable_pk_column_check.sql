SELECT
    C.TABLE_NAME,
    C.CONSTRAINT_NAME,
    CC.COLUMN_NAME,
    T.NULLABLE,
    C.STATUS,
    C.VALIDATED
FROM DBA_CONSTRAINTS C
JOIN DBA_CONS_COLUMNS CC
  ON C.OWNER = CC.OWNER
 AND C.CONSTRAINT_NAME = CC.CONSTRAINT_NAME
JOIN DBA_TAB_COLUMNS T
  ON CC.OWNER = T.OWNER
 AND CC.TABLE_NAME = T.TABLE_NAME
 AND CC.COLUMN_NAME = T.COLUMN_NAME
WHERE C.OWNER = 'SCHEMA1'
  AND C.CONSTRAINT_TYPE = 'P'
  AND T.NULLABLE = 'Y'
ORDER BY C.TABLE_NAME, CC.POSITION;